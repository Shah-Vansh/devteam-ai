"""Generate app/execution/constraints.txt inside an E2B sandbox.

    python scripts/lock_sandbox_packages.py

Installs every allowed package (with the overrides) in a fresh sandbox, then records
`pip freeze`. Running it in the sandbox, not on the host, means the pins match the
sandbox's Python version and platform. Re-run it when the allow-list changes.
"""

import sys
from datetime import date

from e2b import Sandbox

from app.core.config import get_settings
from app.execution.packages import (
    ALLOWED_PACKAGES,
    CONSTRAINTS_FILE,
    OVERRIDES,
    TEST_PACKAGES,
)


def main() -> int:
    settings = get_settings()
    if settings.e2b_api_key is None:
        print("E2B_API_KEY is not set in the root .env", file=sys.stderr)
        return 1
    packages = sorted(set(ALLOWED_PACKAGES.values()) | set(TEST_PACKAGES))
    pins = [f"{name}=={version}" for name, version in OVERRIDES.items()]

    sandbox = Sandbox.create(api_key=settings.e2b_api_key.get_secret_value(), timeout=600)
    try:
        python = sandbox.commands.run("python --version").stdout.strip()
        args = " ".join(f"'{p}'" for p in [*packages, *pins])
        sandbox.commands.run(
            f"pip install --no-input --disable-pip-version-check -q {args}", timeout=480
        )
        frozen = sandbox.commands.run("pip freeze --all --exclude pip --exclude setuptools")
    finally:
        sandbox.kill()

    lines = sorted((line for line in frozen.stdout.splitlines() if "==" in line), key=str.lower)
    header = [
        "# Generated by scripts/lock_sandbox_packages.py. Do not edit by hand.",
        f"# Sandbox {python}, {date.today().isoformat()}",
        f"# Overrides: {', '.join(pins) or 'none'}",
    ]
    CONSTRAINTS_FILE.write_text("\n".join(header + lines) + "\n", encoding="utf-8")
    print(f"wrote {len(lines)} pins to {CONSTRAINTS_FILE}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
